import { chromium, devices } from 'playwright'
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' })
const ctx = await browser.newContext({ ...devices['iPhone 13'], viewport: { width: 390, height: 844 } })
const page = await ctx.newPage()
page.on('pageerror', (e) => console.error('PAGE ERROR', e.message))
page.on('console', (m) => { if (m.type() === 'error') console.error('CONSOLE', m.text().slice(0, 200)) })
try {
  await page.goto('http://localhost:4173/')
  await page.getByLabel('Family code').fill('deer-camp')
  await page.getByRole('button', { name: 'Next' }).click()
  await page.getByRole('button', { name: 'Dad' }).click()
  await page.getByRole('button', { name: /Not now|Continue/ }).click()
  await page.getByText("This weekend's stands").waitFor()
  await page.getByText('Box Blind · Dad').waitFor()
  await page.screenshot({ path: 'e2e/shots/demo-home.png' })
  await page.getByRole('link', { name: 'Calendar' }).click()
  await page.getByText('Mike + friends').first().waitFor()
  await page.getByRole('link', { name: 'Map', exact: true }).click()
  await page.locator('.pin-label', { hasText: 'Box Blind' }).waitFor()
  await page.waitForTimeout(400)
  await page.screenshot({ path: 'e2e/shots/demo-map.png' })
  await page.getByRole('link', { name: 'More' }).click()
  await page.getByRole('button', { name: 'Unlock admin' }).click()
  await page.getByLabel('Admin PIN').fill('4321')
  await page.getByRole('button', { name: 'Unlock' }).click()
  await page.getByText('Admin mode is on').waitFor()
  await page.reload()
  await page.getByText("This weekend's stands").waitFor() // persisted join

  // Phase 4: feeders due on Home, one-tap fill, sighting with photo, harvest with tag, gallery
  await page.getByText('Feeders due').waitFor()
  await page.getByText('Creek Feeder').waitFor()
  await page.getByRole('button', { name: 'Filled it' }).first().click()
  await page.getByText('Filled Creek Feeder').waitFor()
  await page.getByLabel('How much (optional)').fill('150 lb')
  await page.getByRole('button', { name: 'Save' }).click()
  await page.waitForTimeout(300)
  if (await page.getByText('Feeders due').count()) throw new Error('Creek Feeder still due after fill')
  await page.screenshot({ path: 'e2e/shots/demo-home-filled.png' })

  await page.getByRole('link', { name: 'More' }).click()
  await page.getByRole('button', { name: 'Feeders' }).click()
  await page.getByText('Filled it').first().waitFor()
  await page.screenshot({ path: 'e2e/shots/demo-feeders.png' })

  await page.getByRole('button', { name: 'Back' }).click()
  await page.getByRole('button', { name: 'Sightings' }).click()
  await page.getByText('Big 8, heavy').waitFor()
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  await page.getByRole('button', { name: 'Hog', exact: true }).click()
  await page.getByLabel('Looked like').fill('Two big boars')
  await page.getByLabel('How many').fill('2')
  await page.getByLabel('Where').selectOption({ label: 'Plot Feeder · Feeder' })
  await page.getByTestId('photo-library').setInputFiles('e2e/fixtures/photo.jpg')
  await page.waitForTimeout(300)
  await page.screenshot({ path: 'e2e/shots/demo-sighting-form.png' })
  await page.getByRole('button', { name: 'Add sighting' }).click()
  await page.getByText('2 Hog').waitFor()
  await page.getByText('1 photo').waitFor()
  await page.getByText('2 Hog').click()
  await page.locator('img[alt=""]').first().waitFor()
  await page.screenshot({ path: 'e2e/shots/demo-sighting-detail.png' })
  await page.getByText('Close', { exact: true }).click()
  await page.getByRole('button', { name: 'Hog', exact: true }).click() // species chip filter
  await page.waitForTimeout(300)
  if (await page.getByText('Big 8, heavy').count()) throw new Error('species filter did not hide deer')

  await page.getByRole('button', { name: 'Back' }).click()
  await page.getByRole('button', { name: 'Harvests' }).click()
  await page.getByText('10 point').waitFor()
  await page.screenshot({ path: 'e2e/shots/demo-harvests.png' })
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  await page.getByRole('button', { name: 'Doe', exact: true }).click()
  await page.getByLabel('Description or score').fill('Nice doe')
  await page.getByLabel('Tag number').fill('A-9981')
  await page.getByText('Logged on my license').click()
  await page.getByRole('button', { name: 'Post harvest' }).click()
  await page.getByText('Nice doe').waitFor()
  await page.getByText('3 Deer').waitFor() // season totals updated

  await page.getByRole('button', { name: 'Back' }).click()
  await page.getByRole('button', { name: 'Photos' }).click()
  await page.locator('img').first().waitFor()
  await page.screenshot({ path: 'e2e/shots/demo-gallery.png' })

  // Map: feeder pin sheet shows status + recent activity
  await page.getByRole('link', { name: 'Map', exact: true }).click()
  await page.locator('.pin-label', { hasText: 'Plot Feeder' }).waitFor()
  await page.getByRole('button', { name: 'Zoom in' }).click()
  await page.waitForTimeout(400)
  await page.getByRole('button', { name: 'Zoom in' }).click()
  await page.waitForTimeout(400)
  await page.locator('.pin-icon', { hasText: 'Plot Feeder' }).locator('.pin').click()
  await page.getByText('Recent here').waitFor()
  await page.getByText('Two big boars').waitFor()
  await page.screenshot({ path: 'e2e/shots/demo-feeder-pin.png' })
  console.log('DEMO OK')
} catch (e) {
  console.error(String(e).split('\n')[0])
  await page.screenshot({ path: 'e2e/shots/DEMO-FAIL.png' }).catch(() => {})
  process.exitCode = 1
}
await browser.close()
